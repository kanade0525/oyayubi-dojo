// 課題データ。打つかなの列と、その並び順そのものが「教程」になっている。
//
// 親指シフトの離脱は速度で起きない。配列を覚えきる前の数週間で起きる。だから
// ここで一番大事なのは文章の面白さではなく**並び順**で、次の三つを守って組んである。
//
//   1. 覚えるキーを一度に増やさない。ホームポジション10キー → 右手 → 左手、と
//      片手ずつ範囲を広げる。NICOLA派宣言の入門テキスト（古瀬幸広、1992）が
//      Section 4〜6 で採っている順で、実際これがいちばん脱落が少ない。
//   2. 三つの面を混ぜない。単独打鍵で30キーを一周してから同側シフト（別のかな）で
//      もう一周し、交差シフト（濁音・半濁音）はそのあと。同側と交差を最初から
//      混ぜると、出た文字が違ったときに「キーを間違えた」のか「親指を逆にした」のかが
//      自分で切り分けられなくなる。切り分けられない失敗は上達に効かない。
//   3. 手が覚えてから語・文に移る。反復 → 語 → 文の順。反復のうちは意味の無い
//      文字列でよく、意味を持たせるのは指が場所を覚えてからでいい。
//
// 2 の但し書き ── 同時打鍵だけは、面の一周を待たずに一口だけ先に触らせる。
//
// 以前は第一課の 1〜5 が単独打鍵だけで、そのあいだタイミングメーターは
// 「ぴったり0 良い0 ずれ0 不発0」のまま並んでいた。文字キーと親指キーのずれを
// ミリ秒で測って一打ごとに返すのがこのアプリの中身なので、それを一度も見ないまま
// 最初の三十分が終わると、ただのかな入力練習と見分けが付かない。
//
// かといって同側シフトの課題を前に持ってくると 2 が崩れる。そこで basic-2b を
// 一本だけ挟んだ。これが 2 に反しないのは、2 が禁じているのが
// **同側と交差の同居**だからで、basic-2b に出る同時打鍵は同側シフトだけ、しかも
// 直前の basic-1 / basic-2 で場所を覚えたホームの 4 キーに限ってある。
// 生きている面が一つしか無いので、違う字が出たときの原因は「親指を沈め損ねた」か
// 「沈めなくていいのに沈めた」の二つしかなく、どちらも自分の親指の動きなので
// 学習者に見えている。2 が本当に避けたい「左右どちらの親指だったか」という、
// 本人には確かめようのない失敗の形は、交差シフトが出てくるまで起きない。
// 1（覚えるキーを一度に増やさない）にも触っていない。キーは 1 つも増えていない。
//
// 逆に basic-4 / basic-5 は、覚えるキーが一度に十個増える回なので、意図して
// 単独打鍵だけに戻してある（ここは 1 を優先する）。メーターが黙るのは故障ではなく、
// 親指を休ませて場所だけ覚える回だから。note にそう書いてある。
//
// note は今のところ画面に出ていない。app.js が課題について出すのは title だけで、
// note を読む導線がどこにも無い（course.note は出ている）。だから読み手に届くのは
// **title と text だけ**という前提でこのファイルを書く。意味の分からない語で指が
// 止まる課題は、note に語釈を足しても直らないので text そのものを平易にする。
//
// 面の呼び方は規格 §5.3（CONTRACT.md と同じ）。**ここを取り違えると学習者に
// 逆を教えることになる**ので、コース名と説明文はこの定義で書いてある。
//
//   単独打鍵                              … そのキーのかな
//   同側シフト（左手のキー×左親指 / 右手のキー×右親指） … 別のかな
//   交差シフト（左手のキー×右親指 / 右手のキー×左親指） … 主に濁音・半濁音
//
// コースIDは trophies.js の UNLOCKS が名指しで参照しているので変更しないこと
// （basic / dakuten / cross / words / sentence / timing / speed）。解禁条件は
// 面のカバー率で書かれているので、それが一段ずつ満たされるように課題を配った。
// 単独打鍵が一周する basic-4 で dakuten が、同側シフトが一周する basic-7 で cross が、
// 濁音に入った dakuten-2 で words が開く。面を混ぜないという方針と、解禁が
// 一段ずつ来ることが、たまたまではなく同じ理由で両立している。
//
// text に使えるのは assets/data/nicola.js に載っているかなと記号だけ。
// 載っていない字（カタカナ・漢字・空白・「ゐ」「ゑ」など）を一字でも混ぜると、
// その課題は**永久にクリアできない**。tools/ の検査で機械的に確かめている。
// 語の区切りに空白が使えないので、区切りたいときは読点「、」（KeyP 単独）を使う。
//
// 出典。文章コースの sentence-1・2・4・5 は著作権の消滅した作品からで、各課題の note に
// 書名と作者を書いてある（現代仮名遣いに直し、打てない字を避けて表記を整えた）。
// それ以外の文はすべて書き下ろし。
//
// 古典は「古い言い回しの中に、ふつうの語が並んでいる」ものだけ残した。
// sentence-3 に置いていた『平家物語』の冒頭だけは差し替えてある。
// 祇園精舎・諸行無常・沙羅双樹・盛者必衰 と、語そのものを知らないと**かなの切れ目
// すら分からない**仏教語が四つ続き、指が止まる原因が配列ではなく語彙になる。
// 上に書いたとおり note は画面に出ないので、語釈を足しても打っている人には届かない。
// 拗音が密に並ぶという、この一本の稽古上の役目だけを引き継いで書き下ろした。
// 残した三本（枕草子・方丈記・竹取物語）は文法が古いだけで、出てくる語は
// 川・水・山・雲・竹のような日用語なので、意味が取れなくても指は進む。

