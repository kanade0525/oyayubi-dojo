// COURSES に課題IDを書き写すと二重管理になり、片方だけ直したときに静かに壊れる。
// 並び順は LESSONS の並びそのものなので、course.lessons はここで組み立てる。
for (const course of COURSES) {
  course.lessons = LESSONS.filter((l) => l.courseId === course.id).map((l) => l.id);
}

/** 課題を id で引く。見つからなければ null（未知の id はハッシュルーティングで普通に来る） */
export function findLesson(id) {
  return LESSONS.find((l) => l.id === id) || null;
}

/**
 * 次の課題。コースの終わりまで来たら次のコースの先頭に進む。
 * 最後の課題の次は null。ここを循環させると「全部終わった」が表現できなくなる。
 */
export function nextLesson(id) {
  const i = LESSONS.findIndex((l) => l.id === id);
  if (i === -1) return null;
  return LESSONS[i + 1] || null;
}

/** そのコースの課題を並び順のまま返す */
export function lessonsOf(courseId) {
  return LESSONS.filter((l) => l.courseId === courseId);
}

/** コースを id で引く */
export function findCourse(id) {
  return COURSES.find((c) => c.id === id) || null;
}

/** その課題が属するコース。一覧の見出しやパンくずに使う */
export function courseOf(lessonId) {
  const lesson = findLesson(lessonId);
  return lesson ? findCourse(lesson.courseId) : null;
}
