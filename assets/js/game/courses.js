// 検品ラインのコースと、作業品の点の付け方。
//
// コースは「ノルマの点を、制限時間のうちに検品を通した作業品の合計で越えられるか」の三段。
// ノルマ達成・未達の境目を、打つ速さの帯に一つずつ割り当ててある。
//
//   3,000 点 … 60 秒。毎分 150 かなあたりで達成。中級者（120〜180）がちょうど境目をまたぐ
//   5,000 点 … 90 秒。毎分 170 かなあたりで達成。中級の上の方が「あと少し」になる
//   10,000 点 … 120 秒。毎分 200 かなあたりで達成。上級者がやっと届く
//   （ぴったりの上乗せが入るぶん、親指が揃っている人はもう少し遅くても届く）
//
// 境目を速さで揃えたのは、達成・未達の表示を「今の自分はどの帯にいるか」の目安として
// 読めるようにするため。どのコースでも簡単に届くと、達成・未達が何も語らない。
//
// 作業品の点は**かな一字あたりの点 × 字数**だけで決める。打つのは先頭の作業品だけで
// 選べないので、点は「その作業品に要った打鍵の量」をそのまま映せばよい。
//
// ぴったり（同時打鍵のズレが ±15ms 以内）の上乗せは一打 10 点。
// ズレを詰めることが、速さを上げるのと並ぶ稼ぎ方になる大きさにしてある。
// ローマ字には同時打鍵が無いので上乗せも無い（ランキングは入力方式ごとに分ける）。
//
// 2026-11-02 に «回転ずし» から題材だけ替えた（皿 → 検品ラインの作業品、円 → 点、
// コースの値段 → ノルマ）。遊びの仕組みはそのまま。
//
// コースの id はランキングの鍵になるので変えないこと（p3000 / p5000 / p10000）。
// サーバーの「ありえない値」の上限もここの値から計算される（server/src/core.mjs に同じ値を写してある）。

