// 回転ずしのコースと、皿の値付け。
//
// コースは「値段を払って入店し、制限時間のうちに取った皿の合計で元を取れるか」の
// 三段。得・損の境目（損益分岐）を、打つ速さの帯に一つずつ割り当ててある。
// 数値の根拠の試算は docs/game-design.md に書いた。要点だけ。
//
//   お手軽   … 毎分 140 かなあたりでトントン。中級者（120〜180）がちょうど境目をまたぐ
//   おすすめ … 毎分 190 かなあたりでトントン。中級の上の方が「あと少し」になる
//   高級     … 毎分 235 かなあたりでトントン。上級者（250 前後）がやっと得をする
//
// 境目を速さで揃えたのは、得・損の表示を「今の自分はどの帯にいるか」の目安として
// 読めるようにするため。どのコースでも簡単に得できると、得・損が何も語らない。
//
// 皿の値段は**かな一字あたりの単価 × 字数**だけで決める。打つのは先頭の皿だけで
// 皿を選べないので、値段は「その皿に要った打鍵の量」をそのまま映せばよく、
// 長さで割増し・割引きする理由が無い。
// 単価は上のコースほど高い（30 / 40 / 45 円）。高級の皿が安いと看板と逆になる。
//
// ぴったり（同時打鍵のズレが ±15ms 以内）の上乗せは一打 20 円。シフトを使う字は
// 単語のおよそ半分で、ぴったりの割合を 1 割から 6 割に上げると、取る金額が
// 1 割半ほど増える。これは打つ速さを毎分 15 かな上げたのとほぼ同じ効き目。
// ズレを詰めることが、速さを上げるのと並ぶ稼ぎ方になる大きさにしてある。
//
// コースの id はランキングの鍵になるので変えないこと（otegaru / osusume / koukyu）。
// サーバーの「ありえない値」の上限もここの値から計算される。

