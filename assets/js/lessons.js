/**
 * 課題を id で引く。見つからなければ null（未知の id はハッシュルーティングで普通に来る）。
 * 題材（text-…）と «覚える» の段階（l-…~段階）の両方を引く。ここで引けないと、
 * プレイ画面も記録の題名も出ない。
 */
export function findLesson(id) {
  return TEXTS.find((l) => l.id === id) || findPhase(id) || null;
}

/**
 * 次の課題。«覚える» は次の段階 → 次のレッスンへ。題材は一覧の次の一本へ。
 * 最後の次は null（＝結果画面の «次へ» で門に戻る）。循環させると「全部終わった」が表現できなくなる。
 */
export function nextLesson(id) {
  if (findPhase(id)) return nextPhase(id);
  const i = TEXTS.findIndex((l) => l.id === id);
  return i === -1 ? null : TEXTS[i + 1] || null;
}
