// ================================================================ «鍛える» の題材（texts）
//
// なぜ教程と別の置き場にしたか。
//
// 題材は以前 sentence / speed / timing から引いていた。あの三つは「覚える」の教程の
// 一部で、前の課を終えるまで開かない。結果、まっさらな人の «鍛える» には題材が
// 18本ならぶのに、押すと全部ホームへ弾かれていた。**一覧に出ているのに押せない**のが
// いちばん質の悪い壊れ方で、しかも「自分の操作が悪いのか、壊れているのか」が
// 本人には切り分けられない。
//
// 直し方は二つあった。題材から解禁を外すか、解禁されたものだけ一覧に出すか。
// 後者を採らなかったのは、«鍛える» が扱うのは定義上**もう打てる字**だからで
// （CONTRACT.md「違いはひとつだけ」）、そこに「まだ開いていない」という概念が
// そもそも要らない。段階を持たせるべきは «覚える» の側だけ。
//
// そこで texts を作り、次の三つを守る。
//
//   1. COURSES に入れない。COURSES は «覚える» の課の一覧そのもの（app.js の
//      paintLearn がそのまま札にする）なので、入れると第八課のように見えて、
//      解禁の順番があるかのように読める。教程ではないものを教程の並びに置かない。
//   2. LESSONS に入れない。LESSONS の並びは教程の進行で、app.js は
//      「まだ終わっていない先頭」を次の一問に使い、nextLesson は最後で null を返す。
//      ここに55本足すと、speed-6（総仕上げ）の次が題材に流れ込んで、
//      「全部終わった」が表現できなくなる。
//   3. それでも findLesson / lessonsOf / nextLesson からは普通に引けるようにする。
//      引けないとプレイ画面も履歴の題名も出ない。窓口は下でまとめて面倒を見る。
//
// trophies.js の UNLOCKS が名指しする7つのコースID（basic / dakuten / cross /
// words / sentence / timing / speed）はそのまま。texts はどの解禁条件の対象にもならず、
// app.js の isCourseOpen が素通しする（解禁の対象外＝常に開いている）。
//
// 題材の作り方。app.js の materialInfo が本文を数えて特徴を自動で付ける
// （濁音が多い / 同側シフトが多い / 小書き・拗音が多い / ほぼ単独打鍵 / 長め /
// 同時打鍵が主）。だから**狙って偏らせた本文を書けば、そのまま特徴になる**。
// 三つの軸で散らしてある。
//
//   長さ … 短い(30〜50字) / ふつう(51〜90字) / 長い(100〜200字) /
//          長い(400〜900字) / とても長い(1400〜1700字)。
//          自由入力が400字まで通るのに、用意された題材が全部80字以下だと、
//          長く打ち続ける持久力を試す手が自由入力しか無くなる。
//   面   … 濁音づくし / 同側シフトづくし / 小書き・拗音づくし / 単独打鍵だけ /
//          同時打鍵が主 / 三面が均等。弱い面が分かっているとき、それだけ選べる。
//   文体 … 日常会話・説明文・物語・リスト的な短文の連続・数え上げ・地名人名・
//          仕事の言い回し。同じ面でも、語のかたまりの切れ目が違うと難しさが変わる。
//
// 「ほぼ単独打鍵」の題材だけは文にできず、語の並びになっている。単独打鍵で打てる
// かなは 。、．・かきくけこさしすせそたちつてとはひふへほらいうんめね だけで、
// 「の」「に」「を」「あ」「ま行」「や行」がまるごと同側シフト面にあるため、
// 助詞がほとんど使えない。無理に文にすると日本語のほうが壊れるので、語を並べてある。
//
// 400字を超える長い題材（text-61 以降）を後から足した。80〜200字だと、一本が
// 三十秒で終わって「文章を打った」にならない、という声があったため。画面は行を
// 打ち終えると次の行を出す形なので、本文はいくら長くても一度に出る量は変わらない。
// 長さの内訳は、400字前後・700〜900字・1400〜1700字を混ぜてある。**短いものは
// 消していない**。「軽く一本」という用途は別にあり、長さで選べることが要るから、
// 短いのと長いのが一覧に並んでいる状態を保つ。
//
// size は長さの目安（みじかめ / ふつう / ながめ / とてもながい）。字数そのものは
// app.js が本文を数えて出しているので、これは束ねて選ぶための語。境目は
// 100字・400字・1000字。
//
// 長い本文で気を付けたのは、面の偏りが「疲れ方」として出ることと、文体の差が
// 短文より大きく効くこと。話が続く文体（物語・随筆）は、どこまで打ったかを本文の
// ほうが覚えていてくれるので長さに耐える。切れ目の多い文体（説明文・手順書・対話）は
// 途中でやめやすい。長いものは、その両方を半々にしてある。
//
// 出典。著作権の消滅した作品を使ったものは note の冒頭に書名と作者を書いた。
// note は画面に出るので、書くのは読み手に用のあることだけにする。
// それ以外はすべて書き下ろし。古典は現代仮名遣いに直し、打てない字を避けて整えた。
// 引くのは「古い言い回しの中にふつうの語が並んでいる」ものだけにしてある。
// 語そのものを知らないとかなの切れ目すら取れない文だと、指が止まる原因が
// 配列ではなく語彙になり、練習にならない。
//
// 長い引用でもう一つ効いてくるのが**同音異義**。漢字をかなに開くと、文脈の助けが
// 無い語は読み手のなかで像を結ばない（「こうえん」＝公園/講演/後援）。長い本文では
// これが一箇所あるだけで、そこから先ずっと意味を追えなくなる。だから引用でも、
// かなで読めない語は和語の言い方に替えてある（『やまなし』の「黄金」→「こがね」、
// 『ごん狐』の「炒る」は文ごと落とした）。替えたことは note に一言書いてある。
// かぎかっこは打てないので、せりふは地の文に続けた。

