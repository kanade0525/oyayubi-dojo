/** かな一字あたりの点。サーバーの COURSE_LIMITS の ptPerKana と同じ値 */
export const PT_PER_KANA = Object.freeze({ p3000: 20, p5000: 20, p10000: 25 });

/**
 * 作業品一つの点。語の長さだけで決まる。
 * 知らないコースを渡されたら throw する。0 点や NaN の作業品を黙って流すと、
 * 「通したのに点が入らない」不具合が点の付け方の問題に見えてしまう。
 */
export function itemValue(course, word) {
  const unit = PT_PER_KANA[course?.id];
  if (unit === undefined) throw new Error(`知らないコースです: ${course?.id}`);
  return unit * [...word.kana].length;
}

/** ぴったり一打ごとの上乗せ（点）。単打の字には付かない */
export const PERFECT_BONUS = 10;

/**
 * コンボがこの数に達するごとに時間が延びる。
 * 正確さ 95% だと打ち間違いの間隔は平均 20 打なので、丁寧に打てば時々届き、
 * 雑に打てば届かない境目にした。
 */
export const COMBO_STEP = 20;

/** 延長する時間（ms）。中級者の 60 秒で合計 2〜3 秒。効くが勝負は決めない大きさ */
export const COMBO_TIME_BONUS_MS = 1000;
